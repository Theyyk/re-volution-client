using System.Text;
using REvolutionClient.Launcher.Infrastructure;
using REvolutionClient.Launcher.Model;

namespace REvolutionClient.Launcher.Services;

internal sealed class ClientConfigService
{
    private readonly LauncherPaths _paths;

    public ClientConfigService(LauncherPaths paths) => _paths = paths;

    public async Task WriteAsync(ServerManifest server, CancellationToken cancellationToken)
    {
        if (server.Host.IndexOfAny(new[] { '\r', '\n', '{', '}' }) >= 0)
            throw new InvalidDataException("Server host contains unsupported characters.");

        var configDirectory = Path.Combine(_paths.Game, "config");
        Directory.CreateDirectory(configDirectory);
        var target = Path.Combine(configDirectory, "revolutionclient.cfg");
        var temporary = target + ".tmp";
        var content = new StringBuilder()
            .AppendLine("# Generated by RE:volution Client Launcher. Manual changes may be overwritten.")
            .AppendLine("server {")
            .Append("    S:host=").AppendLine(server.Host)
            .Append("    I:port=").AppendLine(server.Port.ToString())
            .AppendLine("}")
            .ToString();
        await File.WriteAllTextAsync(temporary, content, new UTF8Encoding(false), cancellationToken);
        File.Move(temporary, target, true);
    }
}
